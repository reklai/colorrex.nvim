-- Regenerates test/support/reading.lua: every snippet's words, with the capture the
-- highlighter would paint on each and the meaning the lexicon adds, so the reading
-- test runs under plain LuaJIT with no parsers.
--
--   COLORREX_PARSERS=<parser site> COLORREX_QUERIES=<queries runtime> \
--     nvim --headless --clean -l test/support/tools/reading_fixture.lua
local root = vim.fn.fnamemodify(debug.getinfo(1, "S").source:sub(2), ":p:h:h:h:h")
package.path = root .. "/test/support/?.lua;" .. root .. "/lua/?.lua;" .. package.path
for _, path in ipairs({ vim.env.COLORREX_PARSERS, vim.env.COLORREX_QUERIES }) do
  if path and path ~= "" then
    vim.opt.runtimepath:prepend(path)
  end
end
local Captures, Meanings = require("captures"), require("colorrex.meanings")
local out = { "-- Generated by test/support/tools/reading_fixture.lua. Do not edit by hand.", "return {" }
local files = vim.fn.globpath(root .. "/test/support/snippets", "*", false, true)
table.sort(files)
for _, path in ipairs(files) do
  local lang = vim.fn.fnamemodify(path, ":t:r")
  local words = Captures.words(table.concat(vim.fn.readfile(path), "\n"), lang)
  if words then
    local rows, last = {}, 0 -- a line with no words leaves a hole, so count rows by hand
    for _, word in ipairs(words) do
      last = math.max(last, word.row + 1)
      local capture = word.capture and ("@" .. word.capture) or "-"
      -- What the lexicon adds, read as the host reads it: the node's own text, with its
      -- parent at hand; else the word as it appears in the line.
      local function parent()
        return word.parent
      end
      local added
      if capture ~= "-" then
        local bare = word.text:gsub("^:+(%a)", "%1"):gsub(":$", "")
        added = (word.node_text and Meanings.refine(capture, word.node_text, lang, parent))
          or Meanings.refine(capture, word.text, lang, parent) or Meanings.refine(capture, bare, lang, parent)
      end
      rows[word.row + 1] = rows[word.row + 1] or {}
      table.insert(rows[word.row + 1], ("{ %q, %q%s }"):format(word.text, capture, added and (", %q"):format(added) or ""))
    end
    out[#out + 1] = ("  %s = {"):format(lang)
    for index = 1, last do
      out[#out + 1] = "    { " .. table.concat(rows[index] or {}, ", ") .. " },"
    end
    out[#out + 1] = "  },"
  end
end
out[#out + 1] = "}"
vim.fn.writefile(out, root .. "/test/support/reading.lua")
print(("wrote %d languages"):format(#vim.tbl_filter(function(l) return l:match("^  %w+ = {$") end, out)))
